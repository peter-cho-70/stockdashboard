/** 부분 일치 포함 조회: 항목명이 사전 키를 포함하거나 키가 항목명을 포함하는 경우 반환 */
export function getFinanceTermHint(title: string): string | null {
  const t = title.trim();
  // 정확 일치 우선
  if (GLOSSARY[t]) return GLOSSARY[t];
  // 부분 일치 (긴 키 우선)
  const keys = Object.keys(GLOSSARY).sort((a, b) => b.length - a.length);
  for (const key of keys) {
    if (t.includes(key) || key.includes(t)) return GLOSSARY[key];
  }
  return null;
}
